/** @returns {{ title: string; description: string; url: string } | null} */
export function staticMetaFor(pathname) {
  const path = pathname.length > 1 ? pathname.replace(/\/+$/, "") : pathname
  const meta = Object.hasOwn(STATIC_META, path) ? STATIC_META[path] : null
  return meta ? { ...meta, url: `${SITE_URL}${path === "/" ? "/" : path}` } : null
}
